import fs from 'node:fs';
import assert from 'node:assert/strict';
import {uniqueById,groupByCause,causeOf,sameCause} from '../src/lib/kb/causes.ts';
import {deskRef} from '../src/lib/kb/desk-ref.ts';
import {groupByIntakeTag} from '../src/lib/kb/intake.ts';
const base=new URL('../src/lib/data/',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,base)));
const reports=read('reports-4471.json');
const tenants=Object.fromEntries(fs.readdirSync(new URL('tenants/',base)).map(f=>{const t=read('tenants/'+f);return [t.handle,t]}));
const rows=uniqueById(reports).filter(r=>r.mergedInto===4471);
const groups=groupByCause(rows,r=>tenants[r.tenant]);
const intakeGroups=groupByIntakeTag(rows);
assert.equal(reports.length,427);assert.equal(rows.length,412);
assert.deepEqual(Object.fromEntries(groups.map(g=>[g.cause,g.reports.length])),{parser:379,hint:33});
assert.deepEqual(Object.fromEntries(intakeGroups.map(g=>[g.tag,g.reports.length])),{parser:371,hint:41});
const ids=intakeGroups.flatMap(g=>g.reports.map(r=>r.id));
assert.equal(ids.length,rows.length);
assert.equal(new Set(ids).size,rows.length);
assert.deepEqual([...ids].sort(),rows.map(r=>r.id).sort());
assert.equal(groupByIntakeTag([...rows,rows[0]]).flatMap(g=>g.reports).length,rows.length);
for(const group of intakeGroups)assert.ok(group.reports.every(r=>r.meta.intakeTag===group.tag));
assert.ok(read('desk-notes.json').oneDayMove.every(id=>intakeGroups.find(g=>g.tag==='parser').reports.some(r=>r.id===id)));
assert.equal(causeOf({channel:'form'},undefined),null);
assert.equal(sameCause({channel:'form'},tenants['alder.physio'],{channel:'app'},tenants['alder.physio']),false);
assert.equal(sameCause({channel:'app'},tenants['kettle.books'],{channel:'email'},tenants['kettle.books']),true);
fs.mkdirSync(new URL('../evidence/',import.meta.url),{recursive:true});
for(const g of intakeGroups)fs.writeFileSync(new URL(`../evidence/${g.tag}-report-ids.txt`,import.meta.url),g.reports.map(r=>r.id).join('\n')+'\n');
console.log(JSON.stringify({raw:reports.length,unique:rows.length,originalClassifier:groups.map(g=>({cause:g.cause,count:g.reports.length})),ticketsByOriginalIntakeTag:intakeGroups.map(g=>({tag:g.tag,count:g.reports.length})),deskRef:deskRef('ldomzalski-allegro / Codex / S01E03 / 2026-11-03')},null,2));

import fs from 'node:fs';
import assert from 'node:assert/strict';
import {uniqueById,groupByCause,causeOf,sameCause} from '../src/lib/kb/causes.ts';
import {deskRef} from '../src/lib/kb/desk-ref.ts';
import {groupByProblem} from '../src/lib/kb/problems.ts';
const base=new URL('../src/lib/data/',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,base)));
const reports=read('reports-4471.json');
const tenants=Object.fromEntries(fs.readdirSync(new URL('tenants/',base)).map(f=>{const t=read('tenants/'+f);return [t.handle,t]}));
const rows=uniqueById(reports).filter(r=>r.mergedInto===4471);
const groups=groupByCause(rows,r=>tenants[r.tenant]);
const notes=read('desk-notes.json');
const problems=groupByProblem(rows,r=>tenants[r.tenant],notes.oneDayMove);
assert.equal(reports.length,427);assert.equal(rows.length,412);
assert.deepEqual(Object.fromEntries(groups.map(g=>[g.cause,g.reports.length])),{parser:379,hint:33});
assert.deepEqual(Object.fromEntries(problems.map(g=>[g.problem,g.reports.length])),{parser:374,'time-anomaly':5,hint:33});
const problemIds=problems.flatMap(g=>g.reports.map(r=>r.id));
assert.equal(problemIds.length,rows.length);
assert.equal(new Set(problemIds).size,rows.length);
assert.deepEqual([...problemIds].sort(),rows.map(r=>r.id).sort());
const anomalies=problems.find(g=>g.problem==='time-anomaly');
assert.deepEqual(anomalies.reports.map(r=>r.id).sort(),[...notes.oneDayMove].sort());
assert.equal(groupByProblem([...rows,rows[0]],r=>tenants[r.tenant],notes.oneDayMove).flatMap(g=>g.reports).length,rows.length);
assert.equal(causeOf({channel:'form'},undefined),null);
assert.equal(sameCause({channel:'form'},tenants['alder.physio'],{channel:'app'},tenants['alder.physio']),false);
assert.equal(sameCause({channel:'app'},tenants['kettle.books'],{channel:'email'},tenants['kettle.books']),true);
fs.mkdirSync(new URL('../evidence/',import.meta.url),{recursive:true});
for(const g of problems)fs.writeFileSync(new URL(`../evidence/${g.problem}-report-ids.txt`,import.meta.url),g.reports.map(r=>r.id).join('\n')+'\n');
console.log(JSON.stringify({raw:reports.length,unique:rows.length,originalClassifier:groups.map(g=>({cause:g.cause,count:g.reports.length})),tickets:problems.map(g=>({problem:g.problem,count:g.reports.length})),deskRef:deskRef('ldomzalski-allegro / Codex / S01E03 / 2026-11-03')},null,2));
